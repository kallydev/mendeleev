/// An isotope's half-life
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct HalfLife {
    /// The half-life in the [`TimeUnit`]
    pub value: f64,

    /// The uncertainty of the half-life in the [`TimeUnit`]
    pub uncertainty: f64,

    /// The unit used for the measurements
    pub unit: TimeUnit,
}

impl HalfLife {
    /// The [`Self::value`] in seconds
    ///
    /// # Examples
    ///
    /// ```
    /// use mendeleev::{HalfLife, TimeUnit};
    ///
    /// let hl = HalfLife { value: 2.0, uncertainty: 0.1, unit: TimeUnit::Hour };
    /// assert_eq!(hl.seconds(), 7200.0);
    /// ```
    pub fn seconds(&self) -> f64 {
        self.value * self.unit.seconds()
    }
}

impl PartialOrd for HalfLife {
    fn partial_cmp(&self, other: &Self) -> Option<core::cmp::Ordering> {
        self.seconds().partial_cmp(&other.seconds())
    }
}

macro_rules! hl {
    ($value:expr, $unc:expr, $unit:ident) => {
        Some(HalfLife {
            value: $value,
            uncertainty: $unc,
            unit: $unit,
        })
    };
}

